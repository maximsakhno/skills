#!/usr/bin/env bash
# Выводит сжатую версию правил: контекст хука ограничен 10 000 символов, полный свод в него не помещается.
set -euo pipefail

cat <<'EOF'
<clean-writing>
Пользователь установил плагин clean-writing и просит писать по его правилам все ответы в чате и все тексты для людей: описания задач, MR и PR, README, документацию, письма, отчёты, статьи, комментарии на ревью.

Ниже — сжатая версия правил, она действует для каждого ответа. Полный свод с примерами — в скилле `clean-writing:clean-writing`: его загружают перед документом, длинным текстом и правкой чужого текста.

EOF

cat "${CLAUDE_PLUGIN_ROOT}/skills/clean-writing/core.md"

echo '</clean-writing>'
